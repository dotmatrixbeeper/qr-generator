static KANJI: [u16; 65536] = {
    const BYTES: &[u8] = include_bytes!("../build-data/kanji_table.bin");
    let mut table = [u16::MAX; 65536];
    let mut i = 0;
    while i < 65536 {
        table[i] = u16::from_le_bytes([BYTES[i * 2], BYTES[i * 2 + 1]]);
        i += 1;
    }
    table
};

pub fn alphanumeric_value(c: char) -> Option<u8> {
    let cp = c as u32;
    if cp < 128 && ALPHANUMERIC[cp as usize] != 0xFF {
        Some(ALPHANUMERIC[cp as usize])
    } else {
        None
    }
}

pub fn kanji_value(c: char) -> Option<u16> {
    let cp = c as u32;
    if cp < 65536 {
        let v = KANJI[cp as usize];
        if v != 0xFFFF { Some(v) } else { None }
    } else {
        None
    }
}

